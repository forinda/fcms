/**
 * The schema, in kickjs-db's DSL.
 *
 * Three decisions from the dossier are load-bearing and each is documented at
 * the table it shapes rather than here: `org_id` + `site_id` on everything
 * (ADR 0002 seam 1, ADR 0008), `jsonb` for user-defined fields rather than EAV
 * (doc 03 §2), and `spec_patches` carrying an inverse for every change (doc 03).
 *
 * A database built from this file and one built by the ten legacy Drizzle
 * migrations must be the same database — `baseline.test.ts` compares them,
 * because a baseline that differs is a drift error on the first boot of every
 * existing install.
 *
 * One thing Drizzle did that this does not: `$type<…>()` on text columns.
 * Those are narrowed where the row is read instead.
 */
import {
  bigSerial,
  bigint,
  index,
  integer,
  jsonb,
  table,
  text,
  timestamptz,
  unique,
  uuid,
} from "@forinda/kickjs-db";
import type { PatchOp, SiteSpec } from "@forinda-cms/spec";
import { uuidv7 } from "uuidv7";

/**
 * Column shapes every table repeats.
 *
 * Kept in one place because a table that spells out its own key column will
 * eventually spell one of them differently.
 * This schema had **three** id formats before that was true here — a UUID from a
 * repository, a config string from the environment, and `"service:cut"` built by
 * a seed script.
 */

/**
 * The standard primary key: a UUIDv7, generated by Postgres.
 *
 * **v7 over v4** because it embeds a millisecond timestamp in its high bits and
 * therefore sorts by creation time. A v4 scatters inserts across the whole
 * B-tree, splitting pages and dirtying cache lines all over the index; a v7
 * appends, so a table like `entries` writes to the same few pages. That is a
 * real difference on the small box doc 14 targets.
 *
 * **`uuid` over a ULID in `char(26)`**, which this was first: 16 bytes against
 * 30 measured, a native type every driver and tool already understands, and no
 * npm dependency. A ULID is a convention only this codebase knows; a uuid column
 * is not.
 *
 * **Generated twice over**, which is better than either half alone:
 *
 *   - `$defaultFn` (client-side, the `uuidv7` package) so an insert knows its
 *     id without a `RETURNING` round-trip — which is what lets a transaction
 *     build a graph of related rows before writing any of them.
 *   - `default uuidv7()` (server-side, native in Postgres 18) as the safety net
 *     for anything that bypasses the ORM: raw SQL, a seed, someone in `psql`.
 *
 * Either alone leaves a gap. Together, nothing can insert a row without a
 * time-ordered id — which is the part that had actually gone wrong before, when
 * generation was scattered across a repository and a script.
 *
 * A column pointing at another table's `pk()` is a plain `uuid()`: same type,
 * same constraint.
 */
const pk = () =>
  uuid()
    .primaryKey()
    .defaultSql("uuidv7()")
    .$defaultFn(() => uuidv7());
const createdAt = () => timestamptz().notNull().defaultNow();

/**
 * Organizations.
 *
 * A personal account is an organization of one (ADR 0008), created on signup and
 * never labelled as such until a second member or site exists. A single-site
 * self-hosted install has exactly one row here and never shows the word.
 */
export const organizations = table("organizations", {
  /**
   * Supplied by `ORG_ID`, not generated: an id supplied by configuration.
   *
   * `organizations.id` and `sites.id` come from `ORG_ID` and `SITE_ID`, which
   * default to `"default"` on a single-site install. Forcing a uuid there would
   * mean a self-hoster putting an opaque string in their `.env` for no gain —
   * this is the one place a human names a row, and it should stay legible.
   */
  id: text().primaryKey(),
  name: text().notNull(),
  createdAt: createdAt(),
});

/**
 * Sites.
 *
 * A site belongs to exactly one organization (ADR 0010) — no shared ownership,
 * no site in two orgs. Ownership moves by an explicit transfer, never by
 * membership, because shared ownership leaves permission checks, billing and
 * deletion without an authority.
 */
export const sites = table(
  "sites",
  {
    // Supplied by `SITE_ID`, not generated — see `organizations.id`.
    id: text().primaryKey(),
    orgId: text()
      .notNull()
      .references(() => organizations.id, {
        onDelete: "restrict",
        name: "sites_org_id_organizations_id_fk",
      }),
    slug: text().notNull(),
    name: text().notNull(),
    domain: text(),
    /**
     * Internal, and not the plugin API integer (ADR 0003/0012). A bump here is
     * a data migration; an `api` bump is an ecosystem event.
     */
    specVersion: integer().notNull().default(1),
    /**
     * The site's wall-clock timezone.
     *
     * The gap ADR 0014 recorded for `schedule`: availability is computed against
     * server-local time today, which is wrong the moment a business is hosted
     * somewhere it is not. This column is where the fix reads from.
     */
    timezone: text().notNull().default("UTC"),
    createdAt: createdAt(),
  },
  (t) => ({
    sites_org_slug: unique("sites_org_slug").on(t.orgId, t.slug),
    sites_domain: index("sites_domain").on(t.domain),
  }),
);

/**
 * The current spec, one row per site.
 *
 * Stored whole rather than decomposed into tables. The decomposition that
 * matters is the *file* layout (ADR 0006), which is derived; splitting the
 * document across relational tables would buy queryability nobody needs and
 * cost the atomic read every render performs.
 *
 * `jsonb<SiteSpec>()` is a compile-time assertion about what we wrote, so
 * readers still parse — the type says what it should be, the parse says what it
 * is.
 */
export const siteSpecs = table("site_specs", {
  siteId: text()
    .primaryKey()
    .references(() => sites.id, {
      onDelete: "cascade",
      name: "site_specs_site_id_sites_id_fk",
    }),
  orgId: text().notNull(),
  document: jsonb<SiteSpec>().notNull(),
  updatedAt: timestamptz().notNull().defaultNow(),
});

/**
 * Every change, with its inverse. The spine (doc 03).
 *
 * Doc 13's argument that review can move to a non-developer rests on a wrong
 * "yes" being cheap to reverse, and that only holds because the inverse is
 * recorded at the time rather than reconstructed later. `inverse` is `notNull`
 * for exactly that reason — a patch without one is not a patch this system
 * accepts.
 *
 * `seq` is per-site and monotonic, so undo is "apply the inverse of the highest
 * seq" and history reads in order without a timestamp tiebreak.
 */
export const specPatches = table(
  "spec_patches",
  {
    id: bigSerial().primaryKey(),
    siteId: text()
      .notNull()
      .references(() => sites.id, {
        onDelete: "cascade",
        name: "spec_patches_site_id_sites_id_fk",
      }),
    orgId: text().notNull(),
    seq: integer().notNull(),
    /**
     * Who made the change, as a recorded name rather than a foreign key:
     * ADR 0010 requires history to survive a site transfer without leaking the
     * source org's member directory.
     */
    actor: text().notNull(),
    /** Which surface produced it — chat, canvas, cli, mcp — and which harness. */
    source: text().notNull(),
    harness: text(),
    ops: jsonb<PatchOp[]>().notNull(),
    inverse: jsonb<PatchOp[]>().notNull(),
    /** `additive` | `destructive`. */
    classification: text().notNull(),
    /** One sentence a non-developer can verify (doc 13). */
    summary: text().notNull(),
    appliedAt: createdAt(),
    /** Set when undone, so history stays append-only rather than shrinking. */
    revertedAt: timestamptz(),
  },
  (t) => ({
    spec_patches_site_seq: unique("spec_patches_site_seq").on(t.siteId, t.seq),
    spec_patches_site_applied: index("spec_patches_site_applied").on(t.siteId, t.appliedAt),
  }),
);

/**
 * The people who *use* a site, as opposed to the people who run it.
 *
 * A separate table from `owners` on purpose (ADR 0020): a visitor belongs to one
 * site rather than an organisation, signs themselves up, holds no role, and can
 * never write the spec. One table with a weak role would make a permissions bug
 * the difference between "saved a hotel" and "edited the site".
 */
export const visitors = table(
  "visitors",
  {
    id: pk(),
    siteId: text()
      .notNull()
      .references(() => sites.id, {
        onDelete: "cascade",
        name: "visitors_site_id_sites_id_fk",
      }),
    email: text().notNull(),
    /** argon2id — the same hashing the owners use, because two hashers is one that rots. */
    passwordHash: text().notNull(),
    name: text(),
    createdAt: createdAt(),
    lastSeenAt: timestamptz(),
  },
  // Unique per site, not globally: an account on two sites of one agency's
  // clients is two accounts, because they are two businesses.
  (t) => ({ visitors_site_email: unique("visitors_site_email").on(t.siteId, t.email) }),
);

/**
 * Content entries.
 *
 * `data` is `jsonb` rather than EAV — doc 03 §2 settled that on the research:
 * EAV turns a two-condition filter into self-joins per condition and inflates
 * row metadata per attribute.
 *
 * Fields the spec marks filterable get partial expression indexes, emitted by
 * the migration planner (`planner.ts`, which deviates from doc 03's "generated
 * columns" and says why). The GIN index below covers everything else.
 *
 * The cost of `jsonb` is that Postgres enforces no types inside it, so
 * validation is application-side against `packages/spec` — which every write
 * already goes through.
 */
export const entries = table(
  "entries",
  {
    /**
     * A UUIDv7, not the slug.
     *
     * The seed used to build `"service:cut"`, which reads well and breaks the
     * moment a slug changes — every reference would need rewriting. The unique
     * index on (site, type, slug) already enforces the slug's uniqueness; the id
     * only has to be stable.
     */
    id: pk(),
    siteId: text()
      .notNull()
      .references(() => sites.id, {
        onDelete: "cascade",
        name: "entries_site_id_sites_id_fk",
      }),
    orgId: text().notNull(),
    typeKey: text().notNull(),
    slug: text(),
    data: jsonb<Record<string, unknown>>().notNull(),
    status: text().notNull().default("draft"),
    /**
     * The visitor who submitted this, when one did (ADR 0027).
     *
     * Null for everything an owner, the CLI, MCP or the AI writes — none of
     * those is a visitor. Set to null rather than cascading on account
     * deletion: a booking is the *business's* record of a night that was sold,
     * and closing an account does not un-sell it.
     */
    visitorId: uuid().references(() => visitors.id, {
      onDelete: "set_null",
      name: "entries_visitor_id_visitors_id_fk",
    }),
    createdAt: createdAt(),
    updatedAt: timestamptz().notNull().defaultNow(),
  },
  (t) => ({
    entries_site_type_slug: unique("entries_site_type_slug").on(t.siteId, t.typeKey, t.slug),
    entries_site_type: index("entries_site_type").on(t.siteId, t.typeKey),
    entries_data_gin: index("entries_data_gin").on(t.data).using("gin"),
    entries_site_type_status: index("entries_site_type_status").on(t.siteId, t.typeKey, t.status),
    entries_visitor: index("entries_visitor").on(t.siteId, t.visitorId),
  }),
);

/**
 * Media.
 *
 * Content-addressed (ADR 0010), so a copy is a row pointing at an existing blob
 * rather than bytes moved — which is what makes a site transfer fast in the
 * common case and slow only when the storage backend genuinely differs.
 *
 * A null `siteId` means org-scoped and shared across the org's sites. That is
 * the opt-in half of ADR 0010's asymmetry: promoting widens access and is
 * additive; demoting breaks any other site referencing the asset.
 */
export const assets = table(
  "assets",
  {
    // Stable forever: ADR 0010 makes a transfer change rows, never an
    // `asset:` reference inside a spec.
    id: pk(),
    orgId: text().notNull(),
    /** Null means org-scoped, shared across the org's sites (ADR 0010). */
    siteId: text().references(() => sites.id, {
      onDelete: "cascade",
      name: "assets_site_id_sites_id_fk",
    }),
    blobHash: text().notNull(),
    filename: text().notNull(),
    contentType: text().notNull(),
    bytes: integer().notNull(),
    alt: text(),
    createdAt: createdAt(),
  },
  (t) => ({
    assets_org: index("assets_org").on(t.orgId),
    assets_blob: index("assets_blob").on(t.blobHash),
  }),
);

/**
 * The people who can sign in, and their sessions.
 *
 * Phase 0b is one owner per install (ADR 0008 as amended, after the Better Auth
 * spike). The table is shaped for more than one because adding a column later is
 * cheap and adding a table later means migrating sessions — but nothing yet
 * creates a second row.
 */
export const owners = table(
  "owners",
  {
    id: pk(),
    orgId: text()
      .notNull()
      .references(() => organizations.id, {
        onDelete: "cascade",
        name: "owners_org_id_organizations_id_fk",
      }),
    email: text().notNull(),
    /** argon2id. Never a password, never a reversible encoding of one. */
    passwordHash: text().notNull(),
    name: text(),
    /**
     * What this person may do (ADR 0008 §2, ADR 0041).
     *
     * `owner` is the account the install created and the only one that can add
     * or remove people. The rest are ADR 0008's site roles, stored as text
     * rather than a Postgres enum so adding one is a deploy rather than a
     * migration with a lock on it.
     *
     * Defaulted to `owner` so the account that existed before this column did
     * keeps everything it had — a migration that quietly demotes the only
     * person who can sign in is a migration that locks somebody out of their
     * own site.
     */
    role: text().notNull().default("owner"),
    createdAt: createdAt(),
    lastSeenAt: timestamptz(),
  },
  (t) => ({ owners_email: unique("owners_email").on(t.email) }),
);

/**
 * Sessions.
 *
 * Stores a **hash** of the token, not the token. A database read, a backup, or a
 * leaked dump must not hand out live sessions, and hashing is the difference
 * between an exposure and a breach.
 */
export const ownerSessions = table(
  "owner_sessions",
  {
    id: pk(),
    ownerId: uuid()
      .notNull()
      .references(() => owners.id, {
        onDelete: "cascade",
        name: "owner_sessions_owner_id_owners_id_fk",
      }),
    tokenHash: text().notNull(),
    expiresAt: timestamptz().notNull(),
    createdAt: createdAt(),
    userAgent: text(),
    ipAddress: text(),
    /**
     * When this session was last used.
     *
     * The column that makes a sessions screen worth having: "signed in from
     * somewhere on 3 March" is not enough to decide whether a session is yours,
     * and "last used two minutes ago" is.
     */
    lastUsedAt: timestamptz(),
  },
  (t) => ({
    owner_sessions_token: unique("owner_sessions_token").on(t.tokenHash),
    owner_sessions_owner: index("owner_sessions_owner").on(t.ownerId),
  }),
);

/**
 * Failed sign-in attempts.
 *
 * Rate limiting needs to survive a restart and be shared across every process
 * that answers `/admin/login` — an in-memory counter is neither, and on a
 * two-container install it is a lock that protects one of them.
 *
 * Keyed by what was tried and from where. Both matter: locking only by email
 * lets one attacker lock a real owner out of their own site, and locking only
 * by address does nothing to a distributed attempt.
 */
export const loginAttempts = table(
  "login_attempts",
  {
    id: pk(),
    /**
     * What was being attempted.
     *
     * `login` and `submit` share this table because both answer "how often has
     * this address done this lately" — but they must not share a *counter*:
     * without this column, filling a public contact form twenty times
     * rate-limited the owner's own sign-in from the same address, turning spam
     * into a denial of service against the one person who could clear it.
     */
    kind: text().notNull().default("login"),
    /** Lowercased email as submitted — not a foreign key, since it may be nobody. */
    email: text().notNull(),
    ipAddress: text(),
    at: createdAt(),
  },
  (t) => ({
    login_attempts_kind_email_at: index("login_attempts_kind_email_at").on(t.kind, t.email, t.at),
    login_attempts_at: index("login_attempts_at").on(t.at),
  }),
);

export const visitorSessions = table(
  "visitor_sessions",
  {
    id: pk(),
    visitorId: uuid()
      .notNull()
      .references(() => visitors.id, {
        onDelete: "cascade",
        name: "visitor_sessions_visitor_id_visitors_id_fk",
      }),
    /** Hashed, like every other session token this project stores. */
    tokenHash: text().notNull(),
    expiresAt: timestamptz().notNull(),
    createdAt: createdAt(),
    ipAddress: text(),
  },
  (t) => ({
    visitor_sessions_token: unique("visitor_sessions_token").on(t.tokenHash),
    visitor_sessions_visitor: index("visitor_sessions_visitor").on(t.visitorId),
  }),
);

/**
 * What a visitor kept.
 *
 * A join table rather than content (ADR 0020 §5): saves have no fields, never
 * render as a page, and a hundred thousand of them should not sit in the table
 * the site reads to draw itself.
 */
export const visitorSaves = table(
  "visitor_saves",
  {
    id: pk(),
    visitorId: uuid()
      .notNull()
      .references(() => visitors.id, {
        onDelete: "cascade",
        name: "visitor_saves_visitor_id_visitors_id_fk",
      }),
    typeKey: text().notNull(),
    entryId: uuid().notNull(),
    createdAt: createdAt(),
  },
  (t) => ({
    visitor_saves_unique: unique("visitor_saves_unique").on(t.visitorId, t.entryId),
    visitor_saves_visitor: index("visitor_saves_visitor").on(t.visitorId),
  }),
);

/**
 * Money taken from a site's customer, on behalf of the site's owner.
 *
 * Not the platform's own billing (ADR 0011) — this is a salon's deposit and a
 * hotel's booking. It points at an `entry` because the entry *is* the order
 * (ADR 0023 §1): the content type an owner already designed describes what was
 * bought, so a second representation would only mean two places to look.
 *
 * Everything here is written by the platform. Nothing in a spec can set a
 * status, an amount or a reference, and no request from the public internet can
 * either.
 */
export const payments = table(
  "payments",
  {
    id: pk(),
    siteId: text()
      .notNull()
      .references(() => sites.id, {
        onDelete: "cascade",
        name: "payments_site_id_sites_id_fk",
      }),
    orgId: text().notNull(),
    /** What is being paid for. Cascades: a deleted booking has no payment to show. */
    entryId: uuid()
      .notNull()
      .references(() => entries.id, {
        onDelete: "cascade",
        name: "payments_entry_id_entries_id_fk",
      }),
    typeKey: text().notNull(),
    /** The integration key from the spec's `wiring`, and its kind at the time. */
    via: text().notNull(),
    provider: text().notNull(),
    /**
     * Minor units, integer, always.
     *
     * `bigint` because a currency with no minor unit and a large ticket — an
     * IDR hotel booking is eight digits before the cents — reaches the top of a
     * 32-bit integer, and money that overflows is not a bug anyone forgives.
     */
    amount: bigint({ mode: "number" }).notNull(),
    currency: text().notNull(),
    /** pending | paid | failed | expired | refunded (ADR 0023 §4). */
    status: text().notNull().default("pending"),
    /** The provider's own id for this charge. Null until it has one. */
    reference: text(),
    /** How to reach the payer for this charge — a phone number for M-Pesa. */
    payerRef: text(),
    /**
     * What the provider said, for support and disputes.
     *
     * Never a credential: providers echo request fields back, so what goes in
     * here is filtered rather than dumped.
     */
    detail: jsonb<Record<string, unknown>>(),
    createdAt: createdAt(),
    updatedAt: timestamptz().notNull().defaultNow(),
    paidAt: timestamptz(),
  },
  (t) => ({
    // Confirming twice is a no-op, which is what makes a retried callback safe
    // — and every provider that exists retries.
    payments_site_provider_reference: unique("payments_site_provider_reference").on(
      t.siteId,
      t.provider,
      t.reference,
    ),
    payments_site_status: index("payments_site_status").on(t.siteId, t.status),
    payments_entry: index("payments_entry").on(t.entryId),
  }),
);

/**
 * The workflow queue, as a table (ADR 0024 §2).
 *
 * A row per trigger event, claimed by a runner and retried on failure. Postgres
 * rather than Redis, because a self-hosted install is one `docker compose up`
 * (doc 09) and a second piece of infrastructure to run is a reason not to
 * install the product at all. `FOR UPDATE SKIP LOCKED` is what makes this a
 * queue rather than a table people race on.
 *
 * The row is also the audit trail. "Text me when someone books" failing
 * silently is the worst outcome this feature has, so a failure is a row an
 * owner can read, with the error on it, rather than a line in a log nobody
 * opens.
 */
export const workflowRuns = table(
  "workflow_runs",
  {
    id: pk(),
    siteId: text()
      .notNull()
      .references(() => sites.id, {
        onDelete: "cascade",
        name: "workflow_runs_site_id_sites_id_fk",
      }),
    orgId: text().notNull(),
    /** The `logic` key this run is for. */
    workflowKey: text().notNull(),
    /** What fired it: `entry.created`, `schedule`, … */
    trigger: text().notNull(),
    /** The entry the trigger was about, where there was one. */
    entryId: text(),
    /**
     * The dedupe key for a run that must happen once.
     *
     * A scheduled workflow is due at a minute, not continuously: two app
     * instances ticking at the same second would otherwise both enqueue it.
     * Null for event triggers, which are already one event per row.
     */
    dedupe: text(),
    /** pending | running | done | failed */
    status: text().notNull().default("pending"),
    attempts: integer().notNull().default(0),
    /** When this becomes eligible — now, or after a backoff. */
    runAt: timestamptz().notNull().defaultNow(),
    /** What went wrong last time, in the owner's view. */
    lastError: text(),
    /** What each step did, for the run history. */
    detail: jsonb<Record<string, unknown>>(),
    createdAt: createdAt(),
    updatedAt: timestamptz().notNull().defaultNow(),
  },
  (t) => ({
    workflow_runs_dedupe: unique("workflow_runs_dedupe").on(t.siteId, t.workflowKey, t.dedupe),
    // The claim query's index: due, pending, oldest first.
    workflow_runs_due: index("workflow_runs_due").on(t.status, t.runAt),
    workflow_runs_site_created: index("workflow_runs_site_created").on(t.siteId, t.createdAt),
  }),
);

/**
 * Where a visitor is in a journey, and what they have chosen (ADR 0028).
 *
 * The state is a row and the visitor holds an opaque token, rather than a
 * signed cookie carrying the answers: a booking journey accumulates choices, so
 * the payload grows on every request, it is readable by anyone with the device,
 * and the moment a flow carries a price it is a number a client can be tempted
 * to edit. What the customer sends is a request, not a fact.
 */
export const flowSessions = table(
  "flow_sessions",
  {
    id: pk(),
    siteId: text()
      .notNull()
      .references(() => sites.id, {
        onDelete: "cascade",
        name: "flow_sessions_site_id_sites_id_fk",
      }),
    orgId: text().notNull(),
    /** The page and flow this belongs to — one journey per flow per token. */
    pageKey: text().notNull(),
    flowKey: text().notNull(),
    /** Hashed, like every other token this project stores. */
    tokenHash: text().notNull(),
    /**
     * Step key → what was chosen there.
     *
     * A whole row rather than an id: the journey shows what you picked, and a
     * template reads `{{ flow.stylist.name }}` without a second lookup.
     */
    answers: jsonb<Record<string, Record<string, unknown>>>().notNull().default("{}"),
    createdAt: createdAt(),
    updatedAt: timestamptz().notNull().defaultNow(),
    /** 24 hours. Nobody returns to an abandoned booking journey a week later. */
    expiresAt: timestamptz().notNull(),
  },
  (t) => ({
    flow_sessions_token: unique("flow_sessions_token").on(t.tokenHash, t.pageKey, t.flowKey),
    flow_sessions_expiry: index("flow_sessions_expiry").on(t.expiresAt),
  }),
);
